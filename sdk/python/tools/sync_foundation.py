"""Copy the pinned foundation contract and generate its optional Python DTOs.

Run with an extracted checkout of the pinned commit; this never imports server
application code or writes outside sdk/python.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil

COMMIT = "5a5bd297dfc0c9fd704e408a929d56643042c4ba"
SDK = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, type=Path)
    args = parser.parse_args()
    source = args.source.resolve()
    fixtures = SDK / "tests/fixtures/foundation"
    manifest = json.loads((fixtures / "SOURCE.json").read_text(encoding="utf-8"))
    if manifest["commit"] != COMMIT:
        raise SystemExit("foundation provenance commit mismatch")
    for name, expected in manifest["sha256"].items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
            raise SystemExit(f"source differs from pinned foundation: {name}")
    spec = importlib.util.spec_from_file_location("foundation_generate", source / "contracts/generate.py")
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    api = json.loads((source / "contracts/openapi-v1.yaml").read_text(encoding="utf-8"))
    generated = SDK / "campus/generated"
    generated.mkdir(parents=True, exist_ok=True)
    provenance = f"# Foundation source: {COMMIT}; generated by tools/sync_foundation.py.\n"
    (generated / "api.py").write_text(provenance + generator.generate_types(api, "python"), encoding="utf-8")
    fixtures.mkdir(parents=True, exist_ok=True)
    sources = ["contracts/openapi-v1.yaml", "server/campus/dto.py", "contracts/generate.py"]
    sources += [str(path.relative_to(source)).replace("\\", "/") for path in sorted((source / "contracts/fixtures").glob("*.json"))]
    hashes = {name: hashlib.sha256((source / name).read_bytes()).hexdigest() for name in sources}
    shutil.copyfile(source / "contracts/openapi-v1.yaml", fixtures / "openapi-v1.json")
    for path in (source / "contracts/fixtures").glob("*.json"):
        shutil.copyfile(path, fixtures / path.name)
    (fixtures / "SOURCE.json").write_text(json.dumps({"commit": COMMIT, "sha256": hashes}, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
